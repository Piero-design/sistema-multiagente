-- =============================================================================
-- Gestitel PIMS — Extensión del Agente 7: Terceros y contratos de encargo (DPA)
-- Se ejecuta DESPUÉS de gestitel_base_de_datos.sql, sobre el esquema de una
-- empresa (por defecto "demo"). Es idempotente: puede ejecutarse varias veces.
--
-- Uso:
--   psql -U postgres -d gestitel_revision -f agente7_terceros_dpa.sql
--   psql -U postgres -d gestitel_revision -v schema=unsa -f agente7_terceros_dpa.sql
--
-- Sigue las convenciones del Anexo 03: id bigint con identidad, bloque de
-- auditoría (created_*/updated_*/is_deleted/deleted_*), llaves foráneas
-- DEFERRABLE INITIALLY DEFERRED, códigos de negocio con UNIQUE aparte de la PK.
--
-- Diferencia deliberada con el resto del esquema: incluye restricciones CHECK.
-- Las tablas de Gestitel confían esas reglas a Django (Anexo 04), pero este
-- módulo lo alimenta también un agente externo (n8n), así que el motor debe
-- defender los dominios de valores por sí mismo.
--
-- Cambios respecto del borrador del plan (ver bd/PLAN_MIGRACION_BD.md, §A):
--   * requirement_source admite 'M' (Mixta), valor que el agente sí produce.
--   * Sección 8: funciones agente7_guardar_auditoria() y
--     agente7_registrar_decision(). Reciben el registro JSON tal como lo
--     escribe el agente (assets/esquema_salida.json) y hacen la traducción y
--     las inserciones en una sola sentencia, que es lo que admite un nodo
--     Postgres de n8n con parámetros.
-- =============================================================================

