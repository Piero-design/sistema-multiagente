-- -----------------------------------------------------------------------------
-- 1. core_thirdparty — registro de proveedores / terceros que tratan datos
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS core_thirdparty (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    is_deleted       boolean     NOT NULL DEFAULT false,
    deleted_at       timestamptz,
    code             varchar(20)  NOT NULL UNIQUE,          -- TER-001
    name             varchar(200) NOT NULL,                 -- razón social
    tax_id           varchar(20),                           -- RUC u homólogo
    country          varchar(2)   NOT NULL DEFAULT 'PE',    -- ISO 3166-1 alfa-2
    service_description text      NOT NULL,
    contact_name     varchar(150),
    contact_email    varchar(254),
    pims_role        varchar(1)   NOT NULL DEFAULT 'N'
        CHECK (pims_role IN ('E','S','R','N')),             -- Encargado / Sub-encargado / Responsable (rol invertido) / No confirmado
    pii_risk_level   varchar(1)   NOT NULL DEFAULT 'M'
        CHECK (pii_risk_level IN ('A','M','B')),            -- Alto / Medio / Bajo
    certifications   jsonb        NOT NULL DEFAULT '[]',    -- [{"nombre":"ISO 27001","estado":"Verificada con evidencia",...}]
    uses_ai_on_data  boolean      NOT NULL DEFAULT false,
    status           varchar(1)   NOT NULL DEFAULT 'A'
        CHECK (status IN ('A','I')),                        -- Activo / Inactivo
    source           varchar(1)   NOT NULL DEFAULT 'M'
        CHECK (source IN ('M','P')),                        -- Manual / detectado en el Perfil de la organización
    created_by_id    integer NOT NULL REFERENCES auth_user(id) DEFERRABLE INITIALLY DEFERRED,
    updated_by_id    integer          REFERENCES auth_user(id) DEFERRABLE INITIALLY DEFERRED,
    deleted_by_id    integer          REFERENCES auth_user(id) DEFERRABLE INITIALLY DEFERRED
);
COMMENT ON TABLE core_thirdparty IS 'Agente 7: proveedores y terceros que tratan datos personales por cuenta de la organización.';

-- -----------------------------------------------------------------------------
-- 2. core_dpacontract — contrato de encargo de tratamiento
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS core_dpacontract (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    is_deleted       boolean     NOT NULL DEFAULT false,
    deleted_at       timestamptz,
    contract_code    varchar(20)  NOT NULL UNIQUE,          -- código del contrato o H-<sha256 abreviado>
    third_party_id   bigint NOT NULL REFERENCES core_thirdparty(id) DEFERRABLE INITIALLY DEFERRED,   -- PROTECT (app)
    process_id       bigint          REFERENCES core_process(id)    DEFERRABLE INITIALLY DEFERRED,   -- proceso de origen, opcional
    title            varchar(255) NOT NULL,
    contract_type    varchar(1)   NOT NULL DEFAULT 'C'
        CHECK (contract_type IN ('C','A','O')),             -- Contrato / Adenda / Orden de servicio estatal
    signed_date      date,
    start_date       date,
    end_date         date,                                  -- vencido se DERIVA de aquí (sin columna de estado)
    notice_days      integer CHECK (notice_days IS NULL OR notice_days >= 0),   -- preaviso de no renovación
    auto_renewal     boolean NOT NULL DEFAULT false,
    international_transfer boolean NOT NULL DEFAULT false,
    transfer_countries jsonb  NOT NULL DEFAULT '[]',        -- ["Estados Unidos","Irlanda"]
    contract_file    varchar(255),                          -- ruta del archivo protegido
    contract_text_hash varchar(64),                         -- SHA-256 del texto evaluado
    status           varchar(1)   NOT NULL DEFAULT 'B'
        CHECK (status IN ('B','V','T')),                    -- Borrador / Vigente / Terminado
    created_by_id    integer NOT NULL REFERENCES auth_user(id) DEFERRABLE INITIALLY DEFERRED,
    updated_by_id    integer          REFERENCES auth_user(id) DEFERRABLE INITIALLY DEFERRED,
    deleted_by_id    integer          REFERENCES auth_user(id) DEFERRABLE INITIALLY DEFERRED,
    CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);
COMMENT ON TABLE core_dpacontract IS 'Agente 7: contratos de encargo de tratamiento (DPA). El estado «vencido» se deriva de end_date.';

-- Tabla puente: activos de información (Inventario) que cubre el contrato
CREATE TABLE IF NOT EXISTS core_dpacontract_assets (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dpacontract_id bigint NOT NULL REFERENCES core_dpacontract(id) DEFERRABLE INITIALLY DEFERRED,
    asset_id       bigint NOT NULL REFERENCES core_asset(id)       DEFERRABLE INITIALLY DEFERRED,
    UNIQUE (dpacontract_id, asset_id)
);

-- -----------------------------------------------------------------------------
-- 3. core_dpaassessment — cada auditoría del agente sobre un contrato
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS core_dpaassessment (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    is_deleted       boolean     NOT NULL DEFAULT false,
    deleted_at       timestamptz,
    assessment_code  varchar(30) NOT NULL UNIQUE,           -- id del expediente del agente (_registro.id_registro)
    contract_id      bigint NOT NULL REFERENCES core_dpacontract(id) DEFERRABLE INITIALLY DEFERRED,  -- PROTECT (app)
    standard_edition varchar(20) NOT NULL DEFAULT 'ISO27701_2025',
    jurisdiction     varchar(20) NOT NULL DEFAULT 'peru',
    skill_version    varchar(20) NOT NULL,
    model_provider   varchar(30) NOT NULL,                  -- claude_code / ollama / anthropic / openai
    model_name       varchar(100) NOT NULL,
    pii_risk_level   varchar(1)  NOT NULL CHECK (pii_risk_level IN ('A','M','B')),
    score_base       numeric(5,2) CHECK (score_base BETWEEN 0 AND 100),     -- CALCULADO por código
    score            numeric(5,2) CHECK (score BETWEEN 0 AND 100),          -- CALCULADO (con penalizaciones)
    band             varchar(1)  CHECK (band IN ('B','M','A')),             -- riesgo Bajo / Medio / Alto
    verdict          varchar(1)  CHECK (verdict IN ('R','C','N')),          -- Recomendable / con Condiciones / No recomendable
    section_scores   jsonb NOT NULL DEFAULT '{}',          -- {"A.2.2":75,"A.2.3":50,...}
    alerts           jsonb NOT NULL DEFAULT '[]',          -- alertas de riesgo
    renewal_alerts   jsonb NOT NULL DEFAULT '[]',          -- recalculadas cada lunes
    remediation_plan jsonb NOT NULL DEFAULT '[]',
    report_md        text,                                  -- informe de 12 secciones
    result_json      jsonb,                                 -- salida completa validada contra el esquema
    profile_hash     varchar(64),
    profile_validated boolean NOT NULL DEFAULT false,
    approval_status  varchar(1)  NOT NULL DEFAULT 'D'
        CHECK (approval_status IN ('D','L','A','R')),       -- Pendiente DPO / Pendiente Legal / Aprobado / Rechazado
    proposed_risk_id bigint REFERENCES core_riskevaluation(id) DEFERRABLE INITIALLY DEFERRED,  -- SET_NULL: riesgo sugerido (cl. 6.1.2)
    approved_document_id bigint REFERENCES core_document(id) DEFERRABLE INITIALLY DEFERRED,    -- SET_NULL: DPA aprobado en Gestión Documental
    created_by_id    integer NOT NULL REFERENCES auth_user(id) DEFERRABLE INITIALLY DEFERRED,
    updated_by_id    integer          REFERENCES auth_user(id) DEFERRABLE INITIALLY DEFERRED,
    deleted_by_id    integer          REFERENCES auth_user(id) DEFERRABLE INITIALLY DEFERRED
);
COMMENT ON COLUMN core_dpaassessment.score IS 'CALCULADO por código: promedio ponderado x 100 - 5 por alerta Alta (máx. -20). Nunca lo escribe el modelo.';

-- -----------------------------------------------------------------------------
-- 4. core_dpacontrolresult — una fila por cada uno de los 26 controles
