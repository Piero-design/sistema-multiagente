-- Inmutabilidad en el motor (las otras bitácoras la imponen en Django; aquí
-- también escribe n8n, así que se garantiza con un disparador).
CREATE OR REPLACE FUNCTION core_dpaapproval_inmutable() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'core_dpaapproval es inmutable: solo se permiten inserciones.';
END $$;
DROP TRIGGER IF EXISTS trg_dpaapproval_inmutable ON core_dpaapproval;
CREATE TRIGGER trg_dpaapproval_inmutable BEFORE UPDATE OR DELETE ON core_dpaapproval
    FOR EACH ROW EXECUTE FUNCTION core_dpaapproval_inmutable();

-- Turno obligatorio: Legal solo después de una aprobación del DPO.
CREATE OR REPLACE FUNCTION core_dpaapproval_turno() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE ok boolean;
BEGIN
    -- Nombres calificados con el esquema de la tabla: funciona sin search_path.
    IF NEW.step = 'L' THEN
        EXECUTE format('SELECT EXISTS (SELECT 1 FROM %I.core_dpaapproval
                         WHERE assessment_id = $1 AND step = ''D'' AND decision = ''A'')', TG_TABLE_SCHEMA)
           INTO ok USING NEW.assessment_id;
        IF NOT ok THEN
            RAISE EXCEPTION 'Legal no puede decidir antes de que el DPO apruebe (expediente %).', NEW.assessment_id;
        END IF;
    END IF;
    EXECUTE format('UPDATE %I.core_dpaassessment
                       SET approval_status = $1, updated_at = now() WHERE id = $2', TG_TABLE_SCHEMA)
       USING CASE WHEN NEW.decision = 'R' THEN 'R' WHEN NEW.step = 'D' THEN 'L' ELSE 'A' END,
             NEW.assessment_id;
    RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_dpaapproval_turno ON core_dpaapproval;
CREATE TRIGGER trg_dpaapproval_turno BEFORE INSERT ON core_dpaapproval
    FOR EACH ROW EXECUTE FUNCTION core_dpaapproval_turno();

