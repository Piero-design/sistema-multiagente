-- 7. Vistas de explotación (preguntas del profesor)
-- -----------------------------------------------------------------------------
-- Última auditoría vigente de cada contrato
CREATE OR REPLACE VIEW v_dpa_ultima_auditoria AS
SELECT DISTINCT ON (a.contract_id)
       a.contract_id, c.contract_code, c.title, t.code AS third_party_code, t.name AS third_party,
       t.country, a.id AS assessment_id, a.score, a.band, a.verdict, a.approval_status,
       c.end_date, a.created_at AS assessed_at
FROM core_dpaassessment a
JOIN core_dpacontract c ON c.id = a.contract_id AND NOT c.is_deleted
JOIN core_thirdparty  t ON t.id = c.third_party_id AND NOT t.is_deleted
WHERE NOT a.is_deleted
ORDER BY a.contract_id, a.created_at DESC;

-- «¿Qué terceros no cumplen cláusulas?»
CREATE OR REPLACE VIEW v_dpa_terceros_incumplen AS
SELECT u.third_party, u.contract_code, u.score, u.verdict,
       r.control_code, r.result_status, r.severity, r.is_critical, r.finding
FROM v_dpa_ultima_auditoria u
JOIN core_dpacontrolresult r ON r.assessment_id = u.assessment_id
WHERE r.result_status IN ('N','S','P')
ORDER BY r.is_critical DESC, u.score;

-- Controles más incumplidos en toda la cartera de proveedores
CREATE OR REPLACE VIEW v_dpa_controles_mas_incumplidos AS
SELECT r.control_code,
       count(*) FILTER (WHERE r.result_status = 'N')            AS no_cumple,
       count(*) FILTER (WHERE r.result_status IN ('P','S'))     AS parcial_o_sin_evidencia,
       count(*) FILTER (WHERE r.result_status = 'C')            AS cumple,
       round(100.0 * count(*) FILTER (WHERE r.result_status = 'C')
             / NULLIF(count(*) FILTER (WHERE r.result_status <> 'X'), 0), 1) AS pct_cumplimiento
FROM v_dpa_ultima_auditoria u
JOIN core_dpacontrolresult r ON r.assessment_id = u.assessment_id
GROUP BY r.control_code
ORDER BY no_cumple DESC, pct_cumplimiento;

-- Vencimientos y preavisos (estado derivado, igual que los consentimientos)
CREATE OR REPLACE VIEW v_dpa_vencimientos AS
SELECT c.contract_code, t.name AS third_party, c.end_date, c.notice_days,
       c.end_date - current_date AS dias_para_vencer,
       CASE WHEN c.end_date IS NULL                            THEN 'Sin fecha de fin'
            WHEN c.end_date < current_date                     THEN 'Vencido'
            WHEN c.end_date - coalesce(c.notice_days,0) <= current_date + 60 THEN 'Por vencer / preaviso'
            ELSE 'Vigente' END AS situacion
FROM core_dpacontract c
JOIN core_thirdparty t ON t.id = c.third_party_id
WHERE NOT c.is_deleted AND c.status <> 'T'
ORDER BY c.end_date NULLS FIRST;

-- Terceros sin contrato auditado (insumo para «qué falta»)
CREATE OR REPLACE VIEW v_dpa_terceros_sin_auditoria AS
SELECT t.code, t.name, t.pims_role, t.pii_risk_level, t.source
FROM core_thirdparty t
WHERE NOT t.is_deleted AND t.status = 'A'
  AND NOT EXISTS (SELECT 1 FROM v_dpa_ultima_auditoria u WHERE u.third_party_code = t.code);

-- -----------------------------------------------------------------------------
-- 8. Funciones de escritura para n8n y para la migración
-- -----------------------------------------------------------------------------
-- Un nodo Postgres de n8n con parámetros ($1, $2…) usa el protocolo extendido,
-- que no admite varias sentencias (BEGIN; INSERT…; COMMIT;) en una consulta.
-- Por eso la transacción vive en una función: n8n hace una sola llamada,
--   SELECT demo.agente7_guardar_auditoria($1::jsonb, $2, $3);
-- y la función es atómica (si algo falla, no queda nada a medias).
--
-- Recibe el registro tal como lo guarda el agente en datos/registro/<id>.json
-- (esquema assets/esquema_salida.json, ya recalculado por calcular.js), así que
-- la traducción a los códigos de una letra está en un solo lugar y la usan igual
-- n8n y el script de migración. score, band, verdict y severity salen de los
-- campos que calcula el código, nunca de texto del modelo.
CREATE OR REPLACE FUNCTION agente7_guardar_auditoria(p_registro jsonb, p_informe_md text, p_autor_id integer)
RETURNS bigint
LANGUAGE plpgsql
SET search_path FROM CURRENT
AS $$
DECLARE
    r        jsonb := p_registro;
    v_codigo text  := coalesce(r #>> '{_registro,id_registro}', r ->> 'id_evaluacion');
    v_nombre text  := r #>> '{tercero,nombre}';
    v_hash   text  := r #>> '{contrato,hash_documento_sha256}';
    v_ccod   text;
    v_paises jsonb;
    v_tp     bigint;
    v_ct     bigint;
    v_as     bigint;
    v_riesgo text;
    v_secc   jsonb := '{}';
    k text; v jsonb;
BEGIN
    IF v_codigo IS NULL OR v_nombre IS NULL OR r -> 'controles' IS NULL OR r -> 'puntaje_proveedor' IS NULL THEN
        RAISE EXCEPTION 'Registro incompleto: faltan id, tercero.nombre, controles o puntaje_proveedor.';
    END IF;
    IF EXISTS (SELECT 1 FROM core_dpaassessment WHERE assessment_code = v_codigo) THEN
        RAISE EXCEPTION 'La auditoría % ya está en la base.', v_codigo USING ERRCODE = 'unique_violation';
    END IF;

    v_riesgo := CASE r ->> 'nivel_riesgo_pii' WHEN 'Alto' THEN 'A' WHEN 'Bajo' THEN 'B' ELSE 'M' END;

    -- Países fuera de Perú = transferencia internacional
    SELECT coalesce(jsonb_agg(p), '[]') INTO v_paises
    FROM jsonb_array_elements_text(coalesce(r #> '{tercero,paises_tratamiento}', '[]')) p
    WHERE lower(translate(p, 'úÚ', 'uU')) NOT IN ('peru', 'pe');

    -- 1. Proveedor (el esquema del agente no trae RUC: se identifica por nombre)
    LOCK TABLE core_thirdparty IN SHARE ROW EXCLUSIVE MODE;   -- código TER-nnn sin carreras
    SELECT id INTO v_tp FROM core_thirdparty WHERE name = v_nombre AND NOT is_deleted LIMIT 1;
    IF v_tp IS NULL THEN
        INSERT INTO core_thirdparty (code, name, service_description, pims_role, pii_risk_level,
                                     certifications, uses_ai_on_data, created_by_id)
        VALUES ('TER-' || lpad((coalesce((SELECT max(substr(code, 5)::int) FROM core_thirdparty
                                          WHERE code ~ '^TER-[0-9]+$'), 0) + 1)::text, 3, '0'),
                v_nombre,
                coalesce(r #>> '{tercero,servicio}', ''),
                CASE r #>> '{tercero,rol}' WHEN 'Encargado' THEN 'E' WHEN 'Sub-encargado' THEN 'S' ELSE 'N' END,
                v_riesgo,
                coalesce(r -> 'certificaciones', '[]'),
                coalesce(r #>> '{uso_ia,detectado}', 'false') = 'true',
                p_autor_id)
        RETURNING id INTO v_tp;
    ELSE
        UPDATE core_thirdparty
           SET pii_risk_level = v_riesgo, certifications = coalesce(r -> 'certificaciones', certifications),
               uses_ai_on_data = coalesce(r #>> '{uso_ia,detectado}', 'false') = 'true',
               updated_at = now(), updated_by_id = p_autor_id
         WHERE id = v_tp;
    END IF;

    -- 2. Contrato: su código, o uno derivado del hash del texto evaluado
    v_ccod := left(coalesce(nullif(r #>> '{contrato,id_contrato}', ''),
                            'H-' || left(v_hash, 16),
                            'S-' || left(v_codigo, 18)), 20);
    INSERT INTO core_dpacontract (contract_code, third_party_id, title, signed_date, start_date, end_date,
                                  notice_days, auto_renewal, international_transfer, transfer_countries,
                                  contract_text_hash, status, created_by_id)
    VALUES (v_ccod, v_tp,
            left(coalesce(nullif(r #>> '{tercero,servicio}', ''), 'Contrato con ' || v_nombre), 255),
            (r #>> '{contrato,fecha_firma}')::date,
            (r #>> '{contrato,fecha_vigencia_inicio}')::date,
            (r #>> '{contrato,fecha_vigencia_fin}')::date,
            (r #>> '{contrato,preaviso_terminacion_dias}')::int,
            coalesce((r #>> '{contrato,renovacion_automatica}')::boolean, false),
            jsonb_array_length(v_paises) > 0, v_paises, v_hash, 'V', p_autor_id)
    ON CONFLICT (contract_code) DO UPDATE
       SET end_date = EXCLUDED.end_date, notice_days = EXCLUDED.notice_days,
           auto_renewal = EXCLUDED.auto_renewal, contract_text_hash = EXCLUDED.contract_text_hash,
           updated_at = now(), updated_by_id = p_autor_id
    RETURNING id INTO v_ct;

    -- 3. Auditoría. El desglose por sección llega con el nombre de la sección:
    --    se guarda con el código del Anexo A.
    FOR k, v IN SELECT * FROM jsonb_each(coalesce(r #> '{puntaje_proveedor,por_dimension}', '{}')) LOOP
        v_secc := v_secc || jsonb_build_object(
            CASE k WHEN 'Condiciones de recolección y tratamiento'   THEN 'A.2.2'
                   WHEN 'Obligaciones con los titulares'             THEN 'A.2.3'
                   WHEN 'Privacidad desde el diseño y por defecto'   THEN 'A.2.4'
                   WHEN 'Compartición, transferencia y comunicación' THEN 'A.2.5'
                   WHEN 'Consideraciones de seguridad'               THEN 'A.3'
                   ELSE k END, v);
    END LOOP;

    INSERT INTO core_dpaassessment (assessment_code, contract_id, jurisdiction, skill_version, model_provider,
                                    model_name, pii_risk_level, score_base, score, band, verdict, section_scores,
                                    alerts, renewal_alerts, remediation_plan, report_md, result_json,
                                    profile_hash, profile_validated, created_by_id)
    SELECT v_codigo, v_ct,
           coalesce(r #>> '{jurisdiccion,id}', 'peru'),
           coalesce(r #>> '{trazabilidad,version_skill}', '?'),
           coalesce(r #>> '{_registro,proveedor}', 'desconocido'),
           coalesce(r #>> '{_registro,modelo}', coalesce(r #>> '{trazabilidad,evaluador}', 'desconocido')),
           v_riesgo,
           (r #>> '{puntaje_proveedor,base}')::numeric,
           (r #>> '{puntaje_proveedor,valor}')::numeric,
           CASE r #>> '{puntaje_proveedor,banda}' WHEN 'Riesgo bajo' THEN 'B' WHEN 'Riesgo medio' THEN 'M' ELSE 'A' END,
           CASE r ->> 'dictamen' WHEN 'Recomendable' THEN 'R' WHEN 'Recomendable con condiciones' THEN 'C' ELSE 'N' END,
           v_secc,
           coalesce((SELECT jsonb_agg(a) FROM jsonb_array_elements(r -> 'alertas') a
                     WHERE a ->> 'tipo' IS DISTINCT FROM 'Renovación'), '[]'),
           coalesce((SELECT jsonb_agg(a) FROM jsonb_array_elements(r -> 'alertas') a
                     WHERE a ->> 'tipo' = 'Renovación'), '[]'),
           coalesce(r -> 'remediacion', '[]'),
           p_informe_md,
           r,
           r #>> '{organizacion,perfil,hash_sha256}',
           coalesce(r #>> '{organizacion,perfil,estado}', '') ILIKE 'validado%',
           p_autor_id
    RETURNING id INTO v_as;

    -- 4. Los 26 controles. Peso y criticidad salen de la lista fija de la skill
    --    (criterios_semaforo.md), no del modelo.
    INSERT INTO core_dpacontrolresult (assessment_id, control_code, annex_a_control_id, is_critical, weight,
                                       result_status, severity, clause_ref, quote, requirement_source, finding)
    SELECT v_as, c ->> 'control', ac.id, crit, CASE WHEN crit THEN 3 ELSE 1 END,
           CASE c ->> 'estado' WHEN 'Cumple' THEN 'C' WHEN 'Parcial' THEN 'P' WHEN 'Sin evidencia' THEN 'S'
                               WHEN 'No cumple' THEN 'N' WHEN 'No aplica' THEN 'X' END,
           CASE c ->> 'severidad' WHEN 'Baja' THEN 'B' WHEN 'Media' THEN 'M' WHEN 'Alta' THEN 'A'
                                  WHEN 'Crítica' THEN 'C' END,
           left(nullif(c ->> 'clausula_dpa', ''), 100),
           left(nullif(c ->> 'evidencia', ''), 300),
           CASE c ->> 'fuente_requisito' WHEN 'ISO 27701' THEN 'N' WHEN 'Ley aplicable' THEN 'L'
                                         WHEN 'Ley 29733/Reglamento' THEN 'L' WHEN 'Política interna' THEN 'P'
                                         WHEN 'Mixta' THEN 'M' END,
           nullif(c ->> 'observacion', '')
    FROM jsonb_array_elements(r -> 'controles') c
    CROSS JOIN LATERAL (SELECT (c ->> 'control') = ANY (ARRAY['A.2.2.2','A.2.2.3','A.2.4.3','A.2.5.3','A.2.5.7',
                                                              'A.2.5.8','A.2.5.9','A.3.10','A.3.12']) AS crit) k
    -- A.2.x tiene fila propia (ISO27701_2025); A.3.x se resuelve por la equivalencia
    -- declarada en el control ISO 27001 (p. ej. A.5.20 ↔ A.3.10)
    LEFT JOIN LATERAL (
        SELECT x.id FROM core_annexacontrol x
        WHERE (x.code = c ->> 'control' AND x.source_standard = 'ISO27701_2025')
           OR x.equivalent_controls @> jsonb_build_array(jsonb_build_object('code', c ->> 'control'))
        ORDER BY (x.source_standard = 'ISO27701_2025') DESC, x.sort_order
        LIMIT 1) ac ON true;

    RETURN v_as;
END $$;

-- Decisión DPO / Legal con los valores que usa la página ('DPO'|'Legal',
-- 'aprobar'|'rechazar'). El turno y el estado los imponen los disparadores.
CREATE OR REPLACE FUNCTION agente7_registrar_decision(p_assessment_code text, p_rol text, p_decision text,
                                                      p_usuario text, p_cargo text, p_comentario text,
                                                      p_fecha timestamptz DEFAULT now())
RETURNS varchar
LANGUAGE plpgsql
SET search_path FROM CURRENT
AS $$
DECLARE v_as bigint; v_estado varchar;
BEGIN
    SELECT id INTO v_as FROM core_dpaassessment WHERE assessment_code = p_assessment_code AND NOT is_deleted;
    IF v_as IS NULL THEN
        RAISE EXCEPTION 'No existe la auditoría %.', p_assessment_code;
    END IF;
    INSERT INTO core_dpaapproval (assessment_id, step, decision, decided_by_id, decider_name, decider_position,
                                  comment, decided_at)
    VALUES (v_as,
            CASE p_rol WHEN 'DPO' THEN 'D' WHEN 'Legal' THEN 'L' END,
            CASE p_decision WHEN 'aprobar' THEN 'A' WHEN 'rechazar' THEN 'R' END,
            (SELECT id FROM auth_user WHERE username = lower(p_rol)),
            p_usuario, coalesce(nullif(p_cargo, ''), p_rol), coalesce(p_comentario, ''), coalesce(p_fecha, now()));
    SELECT approval_status INTO v_estado FROM core_dpaassessment WHERE id = v_as;
    RETURN v_estado;
END $$;

